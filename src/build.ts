import { joinFrontmatter, splitFrontmatter } from "./frontmatter.ts";
import { classify, type GateLevel, type Tier } from "./gate.ts";
import type { Intent } from "./intent.ts";
import type { Lesson } from "./lessons.ts";
import { normalizeKey, oneLine } from "./text.ts";

/** Where learned edge cases go, inside the skill folder. The name avoids clashing with an adopted skill's own reference files. */
export const EDGE_CASES_FILE = "references/learned-edge-cases.md";

export interface BuildInput {
  name: string;
  /** The owner's steps. Null for an adopted skill whose intent was not approved. */
  intent: Intent | null;
  /** The original SKILL.md of an adopted skill, used when there is no intent. */
  base: string | null;
  /** A description an agent wrote (bluer.json). Wins over the one bluer makes from the intent (design D27). */
  description?: string | null;
  lessons: Lesson[];
  gate: GateLevel;
  today: string;
  runs: number;
  version: number;
}

export interface BuildResult {
  skillMd: string;
  /** Null when there are no edge cases. */
  edgeCasesMd: string | null;
  /** The lessons with statuses updated (archived, expired, or active again). */
  lessons: Lesson[];
  tiers: Record<Tier, Lesson[]>;
}

/**
 * Build SKILL.md from the layers: the owner's intent (or an adopted skill's
 * original text) plus the lessons that pass the learning gate. The result is
 * the same for the same input, so it is easy to test and to diff.
 */
export function buildSkill(input: BuildInput): BuildResult {
  const { intent } = input;
  const stepIndex = new Map((intent?.steps ?? []).map((step, i) => [normalizeKey(step), i] as const));

  const tiers: Record<Tier, Lesson[]> = { rule: [], edge: [], candidate: [], ignored: [], expired: [] };
  const lessons = input.lessons.map((original) => {
    let lesson = original;
    if (lesson.status === "forgotten") return lesson;
    if (intent && lesson.step !== null) {
      const stepExists = stepIndex.has(normalizeKey(lesson.step));
      if (!stepExists) return lesson.status === "archived" ? lesson : { ...lesson, status: "archived" as const };
      if (lesson.status === "archived") lesson = { ...lesson, status: "active" };
    }
    if (lesson.status !== "active") return lesson;
    const tier = classify(lesson, input.gate, input.today, input.runs);
    tiers[tier].push(lesson);
    return tier === "expired" ? { ...lesson, status: "expired" as const } : lesson;
  });

  const skillMd = intent ? renderFromIntent(input, intent, tiers) : renderFromBase(input, tiers);
  const edgeCasesMd = tiers.edge.length > 0 ? renderEdgeCases(input, intent, tiers.edge) : null;
  return { skillMd, edgeCasesMd, lessons, tiers };
}

const NOTICE =
  "<!-- Built by bluer-skills from intent.md and learnings.md. Do not edit this file: " +
  "bluer rebuilds it. Change intent.md, or tell your agent what to do differently. -->";

const EDGE_POINTER = `## Edge cases\n\nRare cases are in [${EDGE_CASES_FILE}](${EDGE_CASES_FILE}). Read it when a step does not go as planned.\n`;

function byStep(intent: Intent | null, lessons: Lesson[]): { perStep: Lesson[][]; general: Lesson[] } {
  const keys = (intent?.steps ?? []).map(normalizeKey);
  const perStep: Lesson[][] = keys.map(() => []);
  const general: Lesson[] = [];
  for (const lesson of lessons) {
    const i = lesson.step === null ? -1 : keys.indexOf(normalizeKey(lesson.step));
    if (i >= 0) perStep[i]?.push(lesson);
    else general.push(lesson);
  }
  return { perStep, general };
}

const bullets = (lessons: Lesson[]): string => lessons.map((l) => `- ${l.text}`).join("\n");

function describe(intent: Intent): string {
  const steps = intent.steps.join("; ");
  return oneLine(`Steps for "${intent.title}": ${steps}. Use when the user asks for "${intent.title}", or for one of these steps.`, 1024);
}

function renderFromIntent(input: BuildInput, intent: Intent, tiers: Record<Tier, Lesson[]>): string {
  const { perStep, general } = byStep(intent, tiers.rule);
  const parts: string[] = [NOTICE, `# ${intent.title}`, "Do these steps in order."];
  if (intent.notes.length > 0) parts.push(`## Notes from the owner\n\n${intent.notes.map((n) => `- ${n}`).join("\n")}`);
  intent.steps.forEach((step, i) => {
    const rules = perStep[i] ?? [];
    parts.push(rules.length > 0 ? `## ${i + 1}. ${step}\n\n${bullets(rules)}` : `## ${i + 1}. ${step}`);
  });
  if (general.length > 0) parts.push(`## General rules\n\n${bullets(general)}`);
  if (tiers.edge.length > 0) parts.push(EDGE_POINTER.trimEnd());

  const data = {
    name: input.name,
    description: input.description || describe(intent),
    metadata: { "built-by": "bluer-skills", version: String(input.version) },
  };
  return joinFrontmatter(data, parts.join("\n\n") + "\n");
}

function renderFromBase(input: BuildInput, tiers: Record<Tier, Lesson[]>): string {
  const { data, body } = splitFrontmatter(input.base ?? "");
  const metadata = typeof data.metadata === "object" && data.metadata !== null ? data.metadata : {};
  const merged = {
    ...data,
    ...(input.description ? { description: input.description } : {}),
    name: input.name,
    metadata: { ...metadata, "built-by": "bluer-skills", version: String(input.version) },
  };
  const parts: string[] = [body.trim()];
  if (tiers.rule.length > 0) parts.push(`## Learned rules\n\n${tiers.rule.map((l) => `- ${l.step ? `${l.step}: ` : ""}${l.text}`).join("\n")}`);
  if (tiers.edge.length > 0) parts.push(EDGE_POINTER.trimEnd());
  return joinFrontmatter(merged, parts.join("\n\n") + "\n");
}

function renderEdgeCases(input: BuildInput, intent: Intent | null, edges: Lesson[]): string {
  const title = intent?.title ?? input.name;
  const parts: string[] = [`# Edge cases: ${title}`, "These cases are rare. Use the one that matches what is happening now."];
  if (intent) {
    const { perStep, general } = byStep(intent, edges);
    intent.steps.forEach((step, i) => {
      const cases = perStep[i] ?? [];
      if (cases.length > 0) parts.push(`## ${i + 1}. ${step}\n\n${bullets(cases)}`);
    });
    if (general.length > 0) parts.push(`## Any step\n\n${bullets(general)}`);
  } else {
    parts.push(edges.map((l) => `- ${l.step ? `${l.step}: ` : ""}${l.text}`).join("\n"));
  }
  return parts.join("\n\n") + "\n";
}
